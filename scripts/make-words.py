#!/usr/bin/env python3
"""Builds public/words.js from the school's sheet plus the commonest English words it leaves out.

Order is by how common a word is in everyday text (the `wordfreq` package, general English), so the words
that unlock the most reading come first. The school's rare spelling words are kept, at the very end.
Run:  pip install wordfreq  &&  python3 scripts/make-words.py
"""
import json, pathlib
from wordfreq import word_frequency, zipf_frequency, top_n_list

ROOT = pathlib.Path(__file__).resolve().parent.parent
school = json.loads((ROOT / "data/school-lists.json").read_text())["lists"]
alt = json.loads((ROOT / "data/alt.json").read_text())
ADD = 200            # common words to add; past this each extra word unlocks under a third of what the first ones do
COMMON = 5.0         # a spelling-list word at or above this Zipf frequency is common enough to count as a reading word
# Common in adult text but not worth a child's time, or not words to put in front of one: names, swearing, news and business vocabulary.
SKIP = set("""shit fuck fucking s john york american president company state states national united god team season game games party
court law war research university data international service services public support based including video news post guys guy yeah per
information social members series south north death office local area general media development million report deal police""".split())
SHOW = {"i'd": "I'd", "i've": "I've", "i'm": "I'm", "i'll": "I'll", "i": "I"}

freq = lambda w: word_frequency(w.lower(), "en")
uniq = lambda ws: list(dict.fromkeys(ws))
high = uniq(w for l in school[:3] for w in l["words"])
spelling = [w for w in uniq(w for l in school[3:] for w in l["words"]) if w not in high]
kept = [w for w in spelling if zipf_frequency(w.lower(), "en") >= COMMON]
rare = [w for w in spelling if w not in kept]
have = {w.lower() for w in high + spelling}
added = [SHOW.get(w, w) for w in top_n_list("en", 4000) if (w.isalpha() or "'" in w) and len(w) > 1 and w not in have and w not in SKIP][:ADD]

core = sorted(high + kept + added, key=lambda w: -freq(w))
rare = sorted(rare, key=lambda w: -freq(w))
lists = [{"id": "r%d" % (i // 100 + 1), "name": "Reading %d" % (i // 100 + 1), "words": core[i:i + 100]} for i in range(0, len(core), 100)]
lists.append({"id": "sp", "name": "School spelling words", "words": rare})
more = {"whole": "hole", "four": "for fore 4", "wait": "weight", "buy": "by bye", "hours": "ours", "seen": "scene", "week": "weak", "read": "red reed",
        "five": "5", "won't": "wont", "they're": "there their", "you're": "your yore", "i'd": "eyed", "isn't": "isnt", "doesn't": "doesnt",
        "says": "sez", "thanks": "thank", "half": "have", "past": "passed", "due": "do dew", "hit": "it", "son": "sun", "meet": "meat", "wear": "where"}
alt = {**more, **alt}
out = ("// The words, most useful to a reader first, and other spellings a dictation engine may print for a correctly read word\n"
       "// (same sound, or US spelling). Generated by scripts/make-words.py: change that, not this file.\n"
       "// No names or other personal details belong in this file.\n"
       "export const LISTS = " + json.dumps(lists, ensure_ascii=False, separators=(",", ":")) + ";\n"
       "export const SCHOOL = " + json.dumps(uniq(w for l in school for w in l["words"]), ensure_ascii=False, separators=(",", ":")) + ";\n"
       "export const ALT = " + json.dumps(alt, ensure_ascii=False, separators=(",", ":")) + ";\n")
(ROOT / "public/words.js").write_text(out)
cov = lambda ws: 100 * sum(map(freq, ws))
print("reading words %d (school %d + kept spelling %d + added %d), covering %.1f%% of text; spelling words at the end %d; total %d"
      % (len(core), len(high), len(kept), len(added), cov(core), len(rare), len(core) + len(rare)))
